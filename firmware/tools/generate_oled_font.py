#!/usr/bin/env python3
"""Generate the fixed UI's 16px Chinese subset; requires Pillow on the host only."""
import argparse
import hashlib
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

SOURCE_SHA256 = "2c76254f6fc379fddfce0a7e84fb5385bb135d3e399294f6eeb6680d0365b74b"
CHARACTERS = sorted(set("曲目已停止缓冲中播放暂停欠载故障无目录未知声"))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    if hashlib.sha256(args.font.read_bytes()).hexdigest() != SOURCE_SHA256:
        parser.error("Expected NotoSansCJKsc-Regular.otf 2.004; source SHA-256 mismatch")
    font = ImageFont.truetype(str(args.font), 16)
    lines = [
        "// Generated by tools/generate_oled_font.py; do not edit glyph rows.",
        "// Discora UI subset, derived from Noto Sans CJK SC 2.004.",
        "// Copyright 2014-2021 Adobe (http://www.adobe.com/).",
        "// SPDX-License-Identifier: OFL-1.1; see ../fonts/OFL-NotoSansCJK.txt.",
        "#pragma once", "#include <stdint.h>",
        "static const struct { char utf8[4]; uint16_t rows[16]; } oled_zh_glyphs[] = {",
    ]
    for char in CHARACTERS:
        image = Image.new("L", (16, 16))
        ImageDraw.Draw(image).text((0, 14), char, font=font, fill=255, anchor="ls")
        rows = [sum(1 << (15 - x) for x in range(16) if image.getpixel((x, y)) >= 96)
                for y in range(16)]
        lines.append('    {"' + char + '", {' + ', '.join(f"0x{row:04x}" for row in rows) + '}},')
    lines.append("};")
    args.output.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
