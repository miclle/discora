#pragma once
#include "sdkconfig.h"

// Exposed GPIO1/2/4..18 plus GPIO41/42; the latter are reserved from external JTAG.
#define DISCORA_CONTROL_GPIO_VALID(pin) (((pin) >= 1 && (pin) <= 18 && (pin) != 3) || (pin) == 41 || (pin) == 42)

#if defined(CONFIG_DISCORA_EJECT_BUTTON)
#if !DISCORA_CONTROL_GPIO_VALID(CONFIG_DISCORA_EJECT_GPIO)
#error "Invalid EJECT control GPIO"
#endif
#if defined(CONFIG_DISCORA_CD_PLAYER_I2S) && (CONFIG_DISCORA_I2S_BCLK == CONFIG_DISCORA_EJECT_GPIO || CONFIG_DISCORA_I2S_LRCK == CONFIG_DISCORA_EJECT_GPIO || CONFIG_DISCORA_I2S_DATA == CONFIG_DISCORA_EJECT_GPIO)
#error "EJECT GPIO conflicts with I2S"
#endif
#if defined(CONFIG_DISCORA_OLED) && (CONFIG_DISCORA_EJECT_GPIO == 10 || CONFIG_DISCORA_EJECT_GPIO == 11)
#error "EJECT GPIO conflicts with OLED"
#endif
#endif

#if defined(CONFIG_DISCORA_PLAY_PAUSE_BUTTON)
#if !DISCORA_CONTROL_GPIO_VALID(CONFIG_DISCORA_PLAY_PAUSE_GPIO)
#error "Invalid PLAY_PAUSE control GPIO"
#endif
#if defined(CONFIG_DISCORA_CD_PLAYER_I2S) && (CONFIG_DISCORA_I2S_BCLK == CONFIG_DISCORA_PLAY_PAUSE_GPIO || CONFIG_DISCORA_I2S_LRCK == CONFIG_DISCORA_PLAY_PAUSE_GPIO || CONFIG_DISCORA_I2S_DATA == CONFIG_DISCORA_PLAY_PAUSE_GPIO)
#error "PLAY_PAUSE GPIO conflicts with I2S"
#endif
#if defined(CONFIG_DISCORA_OLED) && (CONFIG_DISCORA_PLAY_PAUSE_GPIO == 10 || CONFIG_DISCORA_PLAY_PAUSE_GPIO == 11)
#error "PLAY_PAUSE GPIO conflicts with OLED"
#endif
#if defined(CONFIG_DISCORA_EJECT_BUTTON) && CONFIG_DISCORA_PLAY_PAUSE_GPIO == CONFIG_DISCORA_EJECT_GPIO
#error "PLAY_PAUSE GPIO conflicts with EJECT"
#endif
#endif

#if defined(CONFIG_DISCORA_TRACK_BUTTONS)
#if !DISCORA_CONTROL_GPIO_VALID(CONFIG_DISCORA_PREV_GPIO)
#error "Invalid PREV control GPIO"
#endif
#if defined(CONFIG_DISCORA_CD_PLAYER_I2S) && (CONFIG_DISCORA_I2S_BCLK == CONFIG_DISCORA_PREV_GPIO || CONFIG_DISCORA_I2S_LRCK == CONFIG_DISCORA_PREV_GPIO || CONFIG_DISCORA_I2S_DATA == CONFIG_DISCORA_PREV_GPIO)
#error "PREV GPIO conflicts with I2S"
#endif
#if defined(CONFIG_DISCORA_OLED) && (CONFIG_DISCORA_PREV_GPIO == 10 || CONFIG_DISCORA_PREV_GPIO == 11)
#error "PREV GPIO conflicts with OLED"
#endif
#if defined(CONFIG_DISCORA_EJECT_BUTTON) && CONFIG_DISCORA_PREV_GPIO == CONFIG_DISCORA_EJECT_GPIO
#error "PREV GPIO conflicts with EJECT"
#endif
#if defined(CONFIG_DISCORA_PLAY_PAUSE_BUTTON) && CONFIG_DISCORA_PREV_GPIO == CONFIG_DISCORA_PLAY_PAUSE_GPIO
#error "PREV GPIO conflicts with PLAY_PAUSE"
#endif
#endif

#if defined(CONFIG_DISCORA_TRACK_BUTTONS)
#if !DISCORA_CONTROL_GPIO_VALID(CONFIG_DISCORA_NEXT_GPIO)
#error "Invalid NEXT control GPIO"
#endif
#if defined(CONFIG_DISCORA_CD_PLAYER_I2S) && (CONFIG_DISCORA_I2S_BCLK == CONFIG_DISCORA_NEXT_GPIO || CONFIG_DISCORA_I2S_LRCK == CONFIG_DISCORA_NEXT_GPIO || CONFIG_DISCORA_I2S_DATA == CONFIG_DISCORA_NEXT_GPIO)
#error "NEXT GPIO conflicts with I2S"
#endif
#if defined(CONFIG_DISCORA_OLED) && (CONFIG_DISCORA_NEXT_GPIO == 10 || CONFIG_DISCORA_NEXT_GPIO == 11)
#error "NEXT GPIO conflicts with OLED"
#endif
#if defined(CONFIG_DISCORA_EJECT_BUTTON) && CONFIG_DISCORA_NEXT_GPIO == CONFIG_DISCORA_EJECT_GPIO
#error "NEXT GPIO conflicts with EJECT"
#endif
#if defined(CONFIG_DISCORA_PLAY_PAUSE_BUTTON) && CONFIG_DISCORA_NEXT_GPIO == CONFIG_DISCORA_PLAY_PAUSE_GPIO
#error "NEXT GPIO conflicts with PLAY_PAUSE"
#endif
#if defined(CONFIG_DISCORA_TRACK_BUTTONS) && CONFIG_DISCORA_NEXT_GPIO == CONFIG_DISCORA_PREV_GPIO
#error "NEXT GPIO conflicts with PREV"
#endif
#endif
